'use client';

import { useState } from 'react';
import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import { Bell, BellOff, CheckCheck, CircleAlert, Info, ShieldAlert } from 'lucide-react';
import type { AppNotification, NotificationSeverity, NotificationType, Paginated } from '@kampalasmart/shared';
import { NOTIFICATION_SEVERITIES, NOTIFICATION_TYPES } from '@kampalasmart/shared';
import { useAuth } from '@/lib/auth';
import { api, errorMessage } from '@/lib/api';
import { formatDate, relativeTime, titleCase } from '@/lib/format';
import { PermissionNotice } from '@/components/export-button';
import { useToast } from '@/components/toast';
import {
  EmptyState,
  ErrorState,
  PageHeader,
  Pagination,
  SearchInput,
  Spinner,
  StatusBadge,
  TableSkeleton,
  useDebounced,
} from '@/components/ui';

const TYPE_LABELS: Record<NotificationType, string> = {
  LOW_STOCK: 'Low stock',
  CRITICAL_STOCK: 'Critical stock',
  SYNC_FAILED: 'Sync failed',
  SYNC_CONFLICT: 'Sync conflict',
  SECURITY: 'Security',
  REFUND_PENDING: 'Refund pending',
  TRANSFER_PENDING: 'Transfer pending',
  SYSTEM: 'System',
};

function SeverityIcon({ severity }: { severity: NotificationSeverity }) {
  if (severity === 'CRITICAL') return <ShieldAlert className="h-4 w-4" />;
  if (severity === 'WARNING') return <CircleAlert className="h-4 w-4" />;
  return <Info className="h-4 w-4" />;
}

export default function NotificationsPage() {
  const { can } = useAuth();
  const { toast } = useToast();
  const queryClient = useQueryClient();
  const [page, setPage] = useState(1);
  const [search, setSearch] = useState('');
  const debounced = useDebounced(search, 300);
  const [unreadOnly, setUnreadOnly] = useState(false);
  const [type, setType] = useState('');
  const [severity, setSeverity] = useState('');

  const filters = {
    page,
    pageSize: 20,
    search: debounced || undefined,
    unreadOnly: unreadOnly ? true : undefined,
    type: type || undefined,
    severity: severity || undefined,
  };

  const notifications = useQuery({
    queryKey: ['notifications', filters],
    queryFn: () => api.get<Paginated<AppNotification>>('/notifications', filters),
    enabled: can('notifications:read'),
  });

  const unread = useQuery({
    queryKey: ['notification-unread'],
    queryFn: () => api.get<{ count: number }>('/notifications/unread-count'),
    enabled: can('notifications:read'),
  });

  const markRead = useMutation({
    mutationFn: (id: string) => api.post<{ success: boolean }>(`/notifications/${id}/read`),
    onSuccess: async () => {
      await Promise.all([
        queryClient.invalidateQueries({ queryKey: ['notifications'] }),
        queryClient.invalidateQueries({ queryKey: ['notification-unread'] }),
      ]);
    },
    onError: (error) => toast(errorMessage(error), 'error'),
  });

  const markAll = useMutation({
    mutationFn: () => api.post<{ marked: number }>('/notifications/read-all'),
    onSuccess: async (result) => {
      toast(result.marked ? `${result.marked} notification${result.marked === 1 ? '' : 's'} marked as read.` : 'Everything was already read.', 'success');
      await Promise.all([
        queryClient.invalidateQueries({ queryKey: ['notifications'] }),
        queryClient.invalidateQueries({ queryKey: ['notification-unread'] }),
      ]);
    },
    onError: (error) => toast(errorMessage(error), 'error'),
  });

  if (!can('notifications:read')) return <PermissionNotice area="notifications" />;

  const count = unread.data?.count ?? 0;
  const resetPage = () => setPage(1);

  return (
    <div>
      <PageHeader
        title="Notifications"
        eyebrow="What needs attention"
        description={
          count
            ? `${count} unread notification${count === 1 ? '' : 's'}. Alerts are generated by the system from real stock, refund, transfer and sync events.`
            : 'Alerts are generated from real stock, refund, transfer and sync events. Nothing here is simulated.'
        }
        actions={
          <button
            type="button"
            className="btn-secondary btn-sm"
            onClick={() => markAll.mutate()}
            disabled={markAll.isPending || count === 0}
          >
            {markAll.isPending ? <Spinner /> : <CheckCheck className="h-3.5 w-3.5" />}
            Mark all read
          </button>
        }
      />

      <div className="card mb-4 p-3">
        <div className="flex flex-col gap-2 lg:flex-row lg:items-center">
          <SearchInput
            value={search}
            onChange={(value) => {
              setSearch(value);
              resetPage();
            }}
            placeholder="Search title or message…"
            className="lg:w-80"
          />
          <select
            className="select !w-auto text-xs"
            value={type}
            onChange={(event) => {
              setType(event.target.value);
              resetPage();
            }}
            aria-label="Filter by notification type"
          >
            <option value="">All types</option>
            {NOTIFICATION_TYPES.map((option) => (
              <option key={option} value={option}>
                {TYPE_LABELS[option]}
              </option>
            ))}
          </select>
          <select
            className="select !w-auto text-xs"
            value={severity}
            onChange={(event) => {
              setSeverity(event.target.value);
              resetPage();
            }}
            aria-label="Filter by severity"
          >
            <option value="">All severities</option>
            {NOTIFICATION_SEVERITIES.map((option) => (
              <option key={option} value={option}>
                {titleCase(option)}
              </option>
            ))}
          </select>
          <label className="flex items-center gap-2 text-xs text-ink-600">
            <input
              type="checkbox"
              className="h-3.5 w-3.5 rounded border-ink-300 text-brand-600"
              checked={unreadOnly}
              onChange={(event) => {
                setUnreadOnly(event.target.checked);
                resetPage();
              }}
            />
            Unread only
          </label>
        </div>
      </div>

      <div className="card overflow-hidden">
        {notifications.isLoading ? (
          <TableSkeleton rows={6} cols={3} />
        ) : notifications.isError ? (
          <ErrorState message={errorMessage(notifications.error)} onRetry={() => void notifications.refetch()} />
        ) : !notifications.data?.data.length ? (
          <EmptyState
            icon={<BellOff className="h-5 w-5" />}
            title={unreadOnly ? 'You are all caught up' : 'No notifications yet'}
            description={
              unreadOnly
                ? 'There are no unread alerts for this view.'
                : 'Low stock, refund requests, transfer approvals and sync conflicts will appear here as they happen.'
            }
          />
        ) : (
          <>
            <ul className="divide-y divide-ink-100">
              {notifications.data.data.map((notification) => {
                const unreadItem = !notification.readAt;
                return (
                  <li
                    key={notification.id}
                    className={unreadItem ? 'bg-brand-50/40 px-4 py-3' : 'px-4 py-3'}
                  >
                    <div className="flex items-start gap-3">
                      <span
                        className={`mt-0.5 grid h-8 w-8 shrink-0 place-items-center rounded-lg ${
                          notification.severity === 'CRITICAL'
                            ? 'bg-red-50 text-red-600'
                            : notification.severity === 'WARNING'
                              ? 'bg-accent-50 text-accent-700'
                              : 'bg-sky-50 text-sky-700'
                        }`}
                      >
                        <SeverityIcon severity={notification.severity} />
                      </span>
                      <div className="min-w-0 flex-1">
                        <div className="flex flex-wrap items-center gap-2">
                          <p className="text-sm font-semibold text-ink-900">{notification.title}</p>
                          {unreadItem ? <span className="h-1.5 w-1.5 rounded-full bg-brand-600" aria-label="Unread" /> : null}
                          <span className="badge badge-slate">{TYPE_LABELS[notification.type] ?? titleCase(notification.type)}</span>
                          <StatusBadge status={notification.severity} />
                        </div>
                        <p className="mt-1 text-xs leading-relaxed text-ink-600">{notification.body}</p>
                        <p className="mt-1.5 text-[11px] text-ink-400" title={formatDate(notification.createdAt, true)}>
                          {relativeTime(notification.createdAt)} · {formatDate(notification.createdAt, true)}
                        </p>
                      </div>
                      {unreadItem ? (
                        <button
                          type="button"
                          className="btn-ghost btn-sm shrink-0"
                          onClick={() => markRead.mutate(notification.id)}
                          disabled={markRead.isPending}
                        >
                          {markRead.isPending && markRead.variables === notification.id ? <Spinner /> : <Bell className="h-3.5 w-3.5" />}
                          Mark read
                        </button>
                      ) : null}
                    </div>
                  </li>
                );
              })}
            </ul>
            <Pagination
              page={notifications.data.page}
              pageSize={notifications.data.pageSize}
              total={notifications.data.total}
              onPage={setPage}
            />
          </>
        )}
      </div>
    </div>
  );
}
